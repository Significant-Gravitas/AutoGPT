// Builds src/app/kobra.css from the per-component stylesheets Kobra ships
// beside each file in src/components/ui. The registry repeats shared rules
// (the `t-surface` block, `transition-ring`) in every component that uses
// them, so identical top-level blocks are emitted once. Kobra's values for
// tokens the house theme already defines are dropped: the house tokens in
// globals.css are the contract (see MIGRATION.md).
//
//   node scripts/build-kobra-css.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const UI = new URL("../src/components/ui/", import.meta.url);
const OUT = new URL("../src/app/kobra.css", import.meta.url);
const HOUSE_TOKENS = new Set([
  "--success",
  "--warning",
  "--info",
  "--smooth-ring-color",
]);

function splitBlocks(css) {
  const blocks = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < css.length; i++) {
    const ch = css[i];
    if (ch === "{") depth++;
    else if (ch === "}") {
      depth--;
      if (depth === 0) {
        blocks.push(css.slice(start, i + 1).trim());
        start = i + 1;
      }
    }
  }
  const tail = css.slice(start).trim();
  if (tail) blocks.push(tail);
  return blocks.filter(Boolean);
}

function dropHouseTokens(block) {
  if (!/^(:root|\.dark)\s*\{/.test(block)) return block;
  const kept = block
    .split("\n")
    .filter((line) => {
      const name = line.match(/^\s*(--[\w-]+)\s*:/)?.[1];
      return !(name && HOUSE_TOKENS.has(name));
    })
    .join("\n");
  return /\{\s*\}$/.test(kept) ? "" : kept;
}

const seen = new Set();
const out = [];
for (const file of readdirSync(UI)
  .filter((f) => f.endsWith(".css"))
  .sort()) {
  const css = readFileSync(join(UI.pathname, file), "utf8");
  const blocks = splitBlocks(css).map(dropHouseTokens).filter(Boolean);
  const fresh = blocks.filter((b) => {
    const key = b.replace(/\s+/g, " ");
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
  if (fresh.length) out.push(`/* ${file} */`, ...fresh, "");
}
writeFileSync(
  OUT,
  `/* Generated by scripts/build-kobra-css.mjs from src/components/ui/*.css. Do not edit. */\n\n${out.join("\n")}`,
);
console.log(
  `kobra.css: ${out.filter((l) => l.startsWith("/* ")).length} files, ${seen.size} blocks`,
);
