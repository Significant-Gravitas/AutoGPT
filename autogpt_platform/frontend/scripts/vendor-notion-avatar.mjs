// Regenerates src/components/molecules/NotionAvatar/parts.generated.ts from a
// checkout of github.com/Mayandev/notion-avatar.
//
//   node scripts/vendor-notion-avatar.mjs /path/to/notion-avatar
//
// The upstream `preview/` layers are the composable ones: every file is a full
// 1080x1080 artboard, so stacking them in draw order lines the features up.
// (`part/` holds tightly cropped thumbnails for their own picker UI.)

import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const CATEGORIES = [
  "face",
  "nose",
  "mouth",
  "eyes",
  "eyebrows",
  "glasses",
  "hair",
  "accessories",
  "details",
  "beard",
];

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(
  here,
  "..",
  "src",
  "components",
  "molecules",
  "NotionAvatar",
);
const partsFile = join(outDir, "parts.generated.ts");
const metaFile = join(outDir, "metadata.generated.ts");

const root = process.argv[2];
if (!root) {
  console.error(
    "usage: node scripts/vendor-notion-avatar.mjs <notion-avatar checkout>",
  );
  process.exit(1);
}
const previewDir = join(root, "public", "avatar", "preview");

// Two glasses layers carry <mask> elements referenced by url(#id). Ids have to
// be unique per rendered avatar, so they become a placeholder the renderer
// swaps for a per-instance prefix.
function namespaceIds(markup) {
  return markup
    .replace(/\bid="([^"]+)"/g, (_, id) => `id="{{P}}${id}"`)
    .replace(/url\(#([^)]+)\)/g, (_, id) => `url(#{{P}}${id})`);
}

function innerMarkup(raw) {
  return namespaceIds(
    raw
      .replace(/<\?xml[^>]*\?>/g, "")
      .replace(/<svg[^>]*>/, "")
      .replace(/<\/svg>/, "")
      .replace(/<title>[\s\S]*?<\/title>/g, "")
      .replace(/<desc>[\s\S]*?<\/desc>/g, "")
      .replace(/>\s+</g, "><")
      .replace(/\s{2,}/g, " ")
      .trim(),
  );
}

const parts = {};
for (const category of CATEGORIES) {
  const dir = join(previewDir, category);
  const indices = readdirSync(dir)
    .filter((name) => name.endsWith(".svg"))
    .map((name) => Number(name.replace(".svg", "")))
    .sort((a, b) => a - b);
  if (indices.some((value, position) => value !== position)) {
    throw new Error(`${category}: expected contiguous indices from 0`);
  }
  parts[category] = indices.map((index) =>
    innerMarkup(readFileSync(join(dir, `${index}.svg`), "utf8")),
  );
}

const banner = `// Generated by scripts/vendor-notion-avatar.mjs — do not edit by hand.
// Artwork: the "Noto avatar" pack by Felix Wong, CC0. Layers vendored from
// github.com/Mayandev/notion-avatar (MIT). See ./NOTICE.
`;

// Names and counts live apart from the markup: every avatar needs them to
// build a URL, but only the code that actually draws a face should have to
// pull in a few hundred kilobytes of paths.
const metaSource = `${banner}
export const NOTION_CATEGORIES = [
${CATEGORIES.map((category) => `  "${category}",`).join("\n")}
] as const;

export type NotionCategory = (typeof NOTION_CATEGORIES)[number];

/** Side of the square artboard every layer is drawn on. */
export const VIEWBOX = 1080;

export const NOTION_PART_COUNTS: Record<NotionCategory, number> = {
${CATEGORIES.map((category) => `  ${category}: ${parts[category].length},`).join("\n")}
};
`;

const body = CATEGORIES.map(
  (category) =>
    `  ${category}: [\n${parts[category]
      .map((markup) => `    ${JSON.stringify(markup)},`)
      .join("\n")}\n  ],`,
).join("\n");

const partsSource = `${banner}
// Each entry is the inner markup of one 1080x1080 layer. "{{P}}" marks an id
// that must be prefixed per rendered avatar; composeNotionAvatar does this.

import type { NotionCategory } from "./metadata.generated";

export const NOTION_PARTS: Record<NotionCategory, string[]> = {
${body}
};
`;

mkdirSync(outDir, { recursive: true });
writeFileSync(metaFile, metaSource);
writeFileSync(partsFile, partsSource);

const total = CATEGORIES.reduce((sum, c) => sum + parts[c].length, 0);
console.log(
  CATEGORIES.map((c) => `${c}=${parts[c].length}`).join(" "),
  `\ntotal=${total} parts=${partsSource.length}B meta=${metaSource.length}B`,
);
