import { readFileSync } from "node:fs";
import { basename, dirname, resolve } from "node:path";
import { createRequire } from "node:module";
import { build } from "esbuild";

export async function buildOpenUIValidator() {
  const result = await build({
    entryPoints: ["scripts/openui-validator.ts"],
    outfile: "openui-validator.cjs",
    bundle: true,
    platform: "node",
    target: "node20",
    format: "cjs",
    minify: true,
    legalComments: "inline",
    write: false,
    banner: {
      js: "// Generated by pnpm generate:openui. Do not edit. See openui-validator.LICENSE.txt for licenses.",
    },
  });
  const require = createRequire(resolve("package.json"));
  const coreRequire = createRequire(require.resolve("@openuidev/lang-core"));
  const dependencies = [
    [
      "@openuidev/lang-core",
      resolve(dirname(require.resolve("@openuidev/lang-core")), ".."),
    ],
    ...["zod", "ci-info"].map((name) => [
      name,
      dirname(coreRequire.resolve(`${name}/package.json`)),
    ]),
  ];
  const licenses = dependencies
    .map(
      ([name, directory]) =>
        `${name}\n${readFileSync(resolve(directory, "LICENSE"), "utf8").trimEnd()}`,
    )
    .join("\n\n");
  return [
    ...result.outputFiles.map((file) => ({
      name: basename(file.path),
      text: file.text,
    })),
    { name: "openui-validator.LICENSE.txt", text: licenses + "\n" },
  ];
}
