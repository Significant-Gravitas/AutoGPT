    # ── Screenshot ───────────────────────────────────────────────────

    def screenshot(
        self,
        *,
        monitor: int = 0,
        quality: int = 75,
        region: tuple[int, int, int, int] | None = None,
        window_id: str | None = None,
        format: str = "jpeg",
        include_cursor: bool = True,
    ) -> ScreenshotResult:
        if region is not None and window_id is not None:
            raise FeatureNotSupportedError(
                "screenshot.region+window",
                reason="region and window_id are mutually exclusive",
            )

        try:
            import mss  # type: ignore[import-not-found]
            from PIL import Image  # type: ignore[import-untyped]
        except ImportError as exc:
            raise FeatureNotSupportedError(
                "screenshot", reason=f"mss/Pillow missing: {exc}"
            ) from exc

        if window_id is not None:
            # Resolve native handle via Quartz (CGWindowListCreateImage).
            return self._screenshot_window(
                window_id, quality=quality, format=format, include_cursor=include_cursor
            )

        displays = self.display_info()
        if not displays:
            raise FeatureNotSupportedError("screenshot", reason="no displays detected")
        # PROTOCOL.md: monitor -1 captures every monitor stitched together.
        stitched = monitor == -1
        if not stitched and not 0 <= monitor < len(displays):
            monitor = 0

        try:
            with mss.mss() as sct:
                # mss monitor 0 = stitched; +1 to address an individual display.
                mon = sct.monitors[0 if stitched else monitor + 1]
                if region is not None:
                    rx1, ry1, rx2, ry2 = region
                    # Clip the region into the target monitor and convert to
                    # mss's per-monitor-relative space.
                    mx, my, mw, mh = mon["left"], mon["top"], mon["width"], mon["height"]
                    # region is display-global; clamp to this monitor's rect.
                    cx1 = max(rx1, mx)
                    cy1 = max(ry1, my)
                    cx2 = min(rx2, mx + mw)
                    cy2 = min(ry2, my + mh)
                    if cx2 <= cx1 or cy2 <= cy1:
                        raise FeatureNotSupportedError(
                            "screenshot.region",
                            reason=f"region {region} does not intersect monitor {monitor}",
                        )
                    capture = {
                        "left": cx1,
                        "top": cy1,
                        "width": cx2 - cx1,
                        "height": cy2 - cy1,
                    }
                    raw = sct.grab(capture)
                    origin = (cx1, cy1)
                    grabbed_width = cx2 - cx1
                else:
                    raw = sct.grab(mon)
                    origin = (mon["left"], mon["top"])
                    grabbed_width = mon["width"]
                img = Image.frombytes("RGB", raw.size, raw.bgra, "raw", "BGRX")
        except FeatureNotSupportedError:
            raise
        except Exception as exc:
            raise self._screen_recording_or_other(exc)

        index, scale, logical_size = capture_fields(
            displays,
            monitor,
            stitched=stitched,
            virtual_desktop=mon,
            grabbed_width=grabbed_width,
            image_width=img.width,
        )
        if include_cursor:
            try:
                self._composite_cursor(img, origin, scale)
            except Exception:
                logger.debug("cursor composite failed", exc_info=True)

        img_bytes, mime = image_to_base64(img, format=format, quality=quality)
        # NB: image_to_base64 returns bytes; the dispatcher b64-encodes.
        return ScreenshotResult(
            image_bytes=img_bytes,
            mime_type=mime,
            width=img.width,
            height=img.height,
            monitor=index,
            region=region,
            display_scale=scale,
            logical_size=logical_size,
            origin=origin,
            display_id=index,
        )

    def _composite_cursor(self, img: Any, origin: tuple[int, int], scale: float) -> None:
        """Overlay the system cursor at its current location.

        mss doesn't draw the cursor for us on macOS. We get the
        location from Quartz NSEvent and stamp a tiny black arrow —
        good enough for the model to see "there's the cursor" without
        the per-OS cursor-image fetch dance. The location is in points
        and `scale` is image pixels per point.
        """
        try:
            from PIL import ImageDraw  # type: ignore[import-untyped]
            from Quartz import NSEvent  # type: ignore[import-not-found]
        except ImportError:
            return
        try:
            loc = NSEvent.mouseLocation()
            # macOS mouseLocation is bottom-left origin in screen points;
            # we want top-left in the same coord space as our crop.
            primary = self._primary_display_size()
            if primary is None:
                return
            x = round((loc.x - origin[0]) * scale)
            y = round((primary[1] - loc.y - origin[1]) * scale)
            if 0 <= x < img.width and 0 <= y < img.height:
                d = ImageDraw.Draw(img)
                arrow = [(0, 0), (12, 4), (5, 5), (4, 12)]
                d.polygon(
                    [(x + round(dx * scale), y + round(dy * scale)) for dx, dy in arrow],
                    fill=(0, 0, 0),
                )
        except Exception:
            return

    def _primary_display_size(self) -> tuple[int, int] | None:
        try:
            from Quartz import CGDisplayBounds, CGMainDisplayID  # type: ignore[import-not-found]

            bounds = CGDisplayBounds(CGMainDisplayID())
            return int(bounds.size.width), int(bounds.size.height)
        except Exception:
            return None

    def _screen_recording_or_other(self, exc: Exception) -> Exception:
        """Map mss/CG screen-capture failures to PermissionPendingError
        when the failure is a TCC denial (the message text is the
        cheapest signal we have without re-importing Quartz)."""
        msg = str(exc).lower()
        if "screen" in msg and ("permission" in msg or "denied" in msg or "tcc" in msg):
            return PermissionPendingError(
                "screen_recording",
                "darwin",
                hint="System Settings → Privacy & Security → Screen Recording",
            )
        return exc

    def _screenshot_window(
        self,
        window_id: str,
        *,
        quality: int,
        format: str,
        include_cursor: bool,
    ) -> ScreenshotResult:
        try:
            from PIL import Image  # type: ignore[import-untyped]
            from Quartz import (  # type: ignore[import-not-found]
                CGRectNull,
                CGWindowListCreateImage,
                kCGWindowImageBoundsIgnoreFraming,
                kCGWindowListOptionIncludingWindow,
            )
        except ImportError as exc:
            raise FeatureNotSupportedError("screenshot.window", reason=str(exc)) from exc

        entry = self.window_registry.verify(window_id, self._live_fingerprint)
        cg_window_id = int(entry.native_handle)
        rect = CGRectNull
        # The frame is read on both sides of the capture: one that changed in
        # between can't be told apart from the pixels' own.
        frame_before = self._cg_window_frame(cg_window_id)
        # Without IgnoreFraming the image includes the window's shadow and
        # covers more than the bounds that origin and logical_size describe.
        ref = CGWindowListCreateImage(
            rect,
            kCGWindowListOptionIncludingWindow,
            cg_window_id,
            kCGWindowImageBoundsIgnoreFraming,
        )
        frame_after = self._cg_window_frame(cg_window_id)
        if ref is None:
            raise PermissionPendingError(
                "screen_recording",
                "darwin",
                hint="Window capture failed; grant Screen Recording in System Settings.",
            )
        if (
            frame_before is not None
            and frame_after is not None
            and frame_before[0] != frame_after[0]
        ):
            raise FeatureNotSupportedError(
                "screenshot.window",
                reason="the window moved or was resized during the capture; capture it again",
            )
        # Convert CGImage → PIL via a pragmatic png round-trip through
        # Cocoa NSBitmapImageRep (ships in pyobjc; simpler than the
        # CGDataProvider dance).
        try:
            from Cocoa import (  # type: ignore[import-not-found]
                NSBitmapImageRep,
                NSPNGFileType,
            )

            rep = NSBitmapImageRep.alloc().initWithCGImage_(ref)
            png_data = rep.representationUsingType_properties_(NSPNGFileType, {})
            bytes_data = bytes(png_data)
            from io import BytesIO

            img = Image.open(BytesIO(bytes_data))
        except Exception as exc:
            raise FeatureNotSupportedError(
                "screenshot.window", reason=f"CGImage conversion failed: {exc}"
            ) from exc

        # The window may have moved or been resized since window_list, so use
        # its frame at the capture; fall back to the one it was listed with.
        live = frame_after
        if live is not None and live[0][2] > 0 and live[0][3] > 0:
            x, y, w, h = live[0]
            bounds = (x, y, x + w, y + h)
        else:
            bounds = entry.extra.get("bounds", (0, 0, img.width, img.height))
        monitor = self._display_index_for(bounds)
        origin = (int(bounds[0]), int(bounds[1]))
        # The capture comes back at the display's backing resolution, while
        # the window's bounds are in points.
        logical_size = (
            max(int(bounds[2]) - int(bounds[0]), 1),
            max(int(bounds[3]) - int(bounds[1]), 1),
        )
        scale = round(img.width / logical_size[0], 2)
        if include_cursor:
            try:
                self._composite_cursor(img, origin, scale)
            except Exception:
                logger.debug("cursor composite failed", exc_info=True)
        img_bytes, mime = image_to_base64(img, format=format, quality=quality)
        return ScreenshotResult(
            image_bytes=img_bytes,
            mime_type=mime,
            width=img.width,
            height=img.height,
            monitor=monitor,
            region=None,
            display_scale=scale,
            logical_size=logical_size,
            origin=origin,
            display_id=monitor,
        )

    def _display_index_for(self, bounds: tuple[int, int, int, int]) -> int:
        """The display holding the centre of `bounds` (points), else 0."""
        try:
            displays = self.display_info()
        except Exception:
            return 0
        return display_index_for(displays, bounds)

    # ── Input ────────────────────────────────────────────────────────

    def input_action(
        self,
        action: str,
        *,
        coordinate: tuple[int, int] | None = None,
        text: str | None = None,
        key: str | None = None,
        direction: str | None = None,
        clicks: int | None = None,
        button: str | None = None,
        modifiers: list[str] | None = None,
        scroll_amount: int | None = None,
        scroll_direction: str | None = None,
        duration_ms: int | None = None,
        path: list[tuple[int, int]] | None = None,
        paste: bool = False,
        preserve_clipboard: bool = False,
    ) -> None:
        if action == "wait":
            ms = max(0, min(int(duration_ms or 0), 5000))
            time.sleep(ms / 1000.0)
            return

        # Bounds check (Q1) — applies to any action that takes a coordinate.
        if coordinate is not None:
            self._check_bounds(coordinate)
        if path:
            for pt in path:
                self._check_bounds(pt)

        if not self._ax_trusted():
            raise PermissionPendingError(
                "accessibility",
                "darwin",
                hint="System Settings → Privacy & Security → Accessibility",
            )

        try:
            import pyautogui  # type: ignore[import-untyped]
        except ImportError as exc:
            raise FeatureNotSupportedError("input", reason=str(exc)) from exc

        pyautogui.FAILSAFE = True

        if action == "mouse_move" and coordinate:
            pyautogui.moveTo(coordinate[0], coordinate[1])
            return
        if action in ("left_click", "right_click", "double_click", "middle_click", "triple_click"):
            self._click(action, coordinate, modifiers)
            return
        if action == "mouse_down" and coordinate:
            pyautogui.mouseDown(coordinate[0], coordinate[1], button=button or "left")
            return
        if action == "mouse_up" and coordinate:
            pyautogui.mouseUp(coordinate[0], coordinate[1], button=button or "left")
            return
        if action == "drag" and path:
            btn = button or "left"
            pyautogui.moveTo(path[0][0], path[0][1])
            pyautogui.mouseDown(button=btn)
            try:
                for pt in path[1:]:
                    pyautogui.moveTo(pt[0], pt[1], duration=0.01)
            finally:
                release_held(pyautogui, button=btn)
            return
        if action == "type" and text is not None:
            self._type(text, paste=paste, preserve_clipboard=preserve_clipboard)
            return
        if action == "key" and key:
            pyautogui.hotkey(*self._chord(key))
            return
        if action == "hold_key" and key:
            duration = max(0.0, min((duration_ms or 0) / 1000.0, 5.0))
            with holding(pyautogui, self._chord(key)):
                time.sleep(duration)
            return
        if action == "scroll":
            amount = scroll_amount if scroll_amount is not None else (clicks or 3)
            d = scroll_direction or direction or "down"
            sign = 1 if d in ("up", "right") else -1
            scroll = pyautogui.hscroll if d in ("left", "right") else pyautogui.scroll
            with holding(pyautogui, [self._modifier(m) for m in modifiers or []]):
                if coordinate:
                    scroll(sign * amount, x=coordinate[0], y=coordinate[1])
                else:
                    scroll(sign * amount)
            return
        raise FeatureNotSupportedError(action, reason=f"unknown action {action!r}")

    def _click(
        self,
        action: str,
        coordinate: tuple[int, int] | None,
        modifiers: list[str] | None,
    ) -> None:
        import pyautogui  # type: ignore[import-untyped]

        if coordinate is None:
            raise FeatureNotSupportedError(action, reason="coordinate is required")
        with holding(pyautogui, [self._modifier(m) for m in modifiers or []]):
            if action == "left_click":
                pyautogui.click(coordinate[0], coordinate[1])
            elif action == "right_click":
                pyautogui.rightClick(coordinate[0], coordinate[1])
            elif action == "double_click":
                pyautogui.doubleClick(coordinate[0], coordinate[1])
            elif action == "middle_click":
                pyautogui.middleClick(coordinate[0], coordinate[1])
            elif action == "triple_click":
                pyautogui.tripleClick(coordinate[0], coordinate[1])

    @staticmethod
    def _modifier(name: str) -> str:
        return _KEY_ALIASES.get(name.lower(), name)

    @staticmethod
    def _chord(key: str) -> list[str]:
        import pyautogui  # type: ignore[import-untyped]

        return chord_keys(key, _KEY_ALIASES, known=getattr(pyautogui, "KEY_NAMES", None))

    def _check_bounds(self, coordinate: tuple[int, int]) -> None:
        displays = self.display_info()
        bounds = displays_to_bounds_list(displays)
        if not in_any_rect(coordinate, bounds):
            raise InputOutOfBoundsError(coordinate, normalize_displays_for_error(bounds))

    # ── Cursor / display ─────────────────────────────────────────────

    def cursor_position(self) -> tuple[int, int, int]:
        try:
            from Quartz import NSEvent  # type: ignore[import-not-found]
        except ImportError as exc:
            raise FeatureNotSupportedError("cursor.position", reason=str(exc)) from exc
        loc = NSEvent.mouseLocation()
        primary = self._primary_display_size() or (0, 0)
        x = int(loc.x)
        y = int(primary[1] - loc.y)
        # find which monitor contains (x, y)
        displays = self.display_info()
        idx = 0
        for d in displays:
            ox, oy = d.origin
            # The cursor and origins are in points; physical_size is pixels.
            w, h = d.logical_size
            if ox <= x < ox + w and oy <= y < oy + h:
                idx = d.index
                break
        return x, y, idx

    def display_info(self) -> list[DisplayMonitor]:
        # Quartz first (HiDPI scale); mss fallback.
        try:
            from Quartz import (  # type: ignore[import-not-found]
                CGDisplayBounds,
                CGDisplayCopyDisplayMode,
                CGDisplayModeGetPixelHeight,
                CGDisplayModeGetPixelWidth,
                CGDisplayPixelsHigh,
                CGDisplayPixelsWide,
                CGGetActiveDisplayList,
                CGMainDisplayID,
            )

            max_displays = 16
            err, ids, _ = CGGetActiveDisplayList(max_displays, None, None)
            if err != 0 or not ids:
                raise RuntimeError("CGGetActiveDisplayList failed")
            main = CGMainDisplayID()
            out: list[DisplayMonitor] = []
            for i, did in enumerate(ids):
                bounds = CGDisplayBounds(did)
                logical_w = int(bounds.size.width)
                logical_h = int(bounds.size.height)
                # CGDisplayPixelsWide gives the mode's size in points on a
                # Retina display; the mode's pixel size is the backing store.
                mode = CGDisplayCopyDisplayMode(did)
                if mode is not None:
                    physical_w = int(CGDisplayModeGetPixelWidth(mode))
                    physical_h = int(CGDisplayModeGetPixelHeight(mode))
                else:
                    physical_w = int(CGDisplayPixelsWide(did))
                    physical_h = int(CGDisplayPixelsHigh(did))
                scale = round(physical_w / logical_w, 2) if logical_w else 1.0
                out.append(
                    DisplayMonitor(
                        index=i,
                        primary=(did == main),
                        physical_size=(physical_w, physical_h),
                        logical_size=(logical_w, logical_h),
                        scale=scale,
                        origin=(int(bounds.origin.x), int(bounds.origin.y)),
                    )
                )
            return out
        except Exception:
            ms = displays_via_mss()
            if ms:
                return ms
            raise FeatureNotSupportedError("display.info", reason="no display backend")

    # ── Windows ──────────────────────────────────────────────────────

    def window_list(
        self,
        *,
        app_bundle_id: str | None = None,
        include_minimized: bool = False,
        include_offscreen: bool = False,
    ) -> list[WindowInfo]:
        try:
            from Quartz import (  # type: ignore[import-not-found]
                CGWindowListCopyWindowInfo,
                kCGNullWindowID,
                kCGWindowListExcludeDesktopElements,
                kCGWindowListOptionOnScreenOnly,
            )
        except ImportError as exc:
            raise FeatureNotSupportedError("window.list", reason=str(exc)) from exc

        opts = kCGWindowListExcludeDesktopElements
        # Minimized windows are off screen. Telling them apart from windows on
        # other Spaces needs each window's Accessibility state, so both are
        # listed and is_minimized stays false.
        if not (include_offscreen or include_minimized):
            opts |= kCGWindowListOptionOnScreenOnly
        info = CGWindowListCopyWindowInfo(opts, kCGNullWindowID)
        # Clear stale mappings — the Q2 contract says window_ids are
        # only valid for one LIST/USE cycle. We don't wipe (HELLO does
        # that) but we also don't carry stale entries forward.
        self.window_registry.clear()
        out: list[WindowInfo] = []
        focused_pid = self._focused_pid()
        for entry in info:
            try:
                cg_id = int(entry.get("kCGWindowNumber", 0))
                pid = int(entry.get("kCGWindowOwnerPID", 0))
                if pid == 0 or cg_id == 0:
                    continue
                owner_name = entry.get("kCGWindowOwnerName") or ""
                title = entry.get("kCGWindowName") or ""
                bnds = entry.get("kCGWindowBounds") or {}
                x = int(bnds.get("X", 0))
                y = int(bnds.get("Y", 0))
                w = int(bnds.get("Width", 0))
                h = int(bnds.get("Height", 0))
                bundle = self._bundle_for_pid(pid)
                if app_bundle_id and bundle != app_bundle_id:
                    continue
                fp = WindowFingerprint(
                    pid=pid,
                    class_name=owner_name,
                    creation_timestamp=None,
                )
                monitor = self._display_index_for((x, y, x + w, y + h))
                wid = self.window_registry.mint(
                    cg_id,
                    fp,
                    extra={
                        "bounds": (x, y, x + w, y + h),
                        "monitor": monitor,
                    },
                )
                out.append(
                    WindowInfo(
                        window_id=wid,
                        pid=pid,
                        app_name=str(owner_name),
                        app_bundle_id=bundle,
                        title=str(title) if title else None,
                        bounds=(x, y, x + w, y + h),
                        monitor=monitor,
                        is_focused=(pid == focused_pid),
                        is_minimized=False,
                        is_fullscreen=False,
                    )
                )
            except Exception:
                logger.debug("skipping unparseable window entry", exc_info=True)
        return out

    def _live_fingerprint(self, cg_window_id: Any) -> WindowFingerprint | None:
        try:
            from Quartz import (  # type: ignore[import-not-found]
                CGWindowListCopyWindowInfo,
                kCGWindowListOptionIncludingWindow,
            )

            info = CGWindowListCopyWindowInfo(kCGWindowListOptionIncludingWindow, int(cg_window_id))
            if not info:
                return None
            entry = info[0]
            return WindowFingerprint(
                pid=int(entry.get("kCGWindowOwnerPID", 0)),
                class_name=entry.get("kCGWindowOwnerName") or "",
                creation_timestamp=None,
            )
        except Exception:
            return None

    def _focused_pid(self) -> int | None:
        try:
            from AppKit import NSWorkspace  # type: ignore[import-not-found]

            front = NSWorkspace.sharedWorkspace().frontmostApplication()
            if front is None:
                return None
            return int(front.processIdentifier())
        except Exception:
            return None

    def _bundle_for_pid(self, pid: int) -> str | None:
        try:
            from AppKit import NSRunningApplication  # type: ignore[import-not-found]

            app = NSRunningApplication.runningApplicationWithProcessIdentifier_(pid)
            if app is None:
                return None
            return str(app.bundleIdentifier() or "") or None
        except Exception:
            return None

    def window_focus(self, window_id: str, *, raise_: bool = True) -> None:
        entry = self.window_registry.verify(window_id, self._live_fingerprint)
        if not self._ax_trusted():
            raise PermissionPendingError("accessibility", "darwin")
        try:
            from AppKit import NSRunningApplication  # type: ignore[import-not-found]
        except ImportError as exc:
            raise FeatureNotSupportedError("window.focus", reason=str(exc)) from exc
        live = self._live_fingerprint(entry.native_handle)
        if live is None or live.pid == 0:
            from ..errors import WindowStaleError

            raise WindowStaleError(window_id)
        app = NSRunningApplication.runningApplicationWithProcessIdentifier_(live.pid)
        if app is None:
            from ..errors import WindowStaleError

            raise WindowStaleError(window_id)
        # Activating the app alone brings forward whichever of its windows was
        # last in front, so the chosen window is raised through Accessibility.
        window = self._ax_window_for(live.pid, entry.native_handle)
        if window is None or not self._ax_raise(window):
            from ..errors import WindowStaleError

            raise WindowStaleError(
                window_id,
                message=f"window_id {window_id} could not be raised through Accessibility",
            )
        # NSApplicationActivateIgnoringOtherApps = 2: the app comes to the
        # front with the raised window on top. If it doesn't, later input
        # would go to whichever app is in front.
        if not app.activateWithOptions_(2):
            from ..errors import WindowStaleError

            raise WindowStaleError(
                window_id,
                message=f"macOS did not bring the app of window_id {window_id} to the front",
            )

    def _ax_window_for(self, pid: int, cg_window_id: Any) -> Any | None:
        """The app's Accessibility window that is this CoreGraphics window: the
        one with its frame, and its title when frames alone don't single one
        out. None unless exactly one matches."""
        target = self._cg_window_frame(cg_window_id)
        if target is None:
            return None
        frame, title = target
        matches = [w for w in self._ax_windows(pid) if self._ax_frame(w) == frame]
        if len(matches) > 1 and title:
            matches = [w for w in matches if self._ax_title(w) == title]
        return matches[0] if len(matches) == 1 else None

    def _cg_window_frame(self, cg_window_id: Any) -> tuple[tuple[int, int, int, int], str] | None:
        try:
            from Quartz import (  # type: ignore[import-not-found]
                CGWindowListCopyWindowInfo,
                kCGWindowListOptionIncludingWindow,
            )

            info = CGWindowListCopyWindowInfo(kCGWindowListOptionIncludingWindow, int(cg_window_id))
            if not info:
                return None
            bounds = info[0].get("kCGWindowBounds") or {}
            frame = (
                round(bounds.get("X", 0)),
                round(bounds.get("Y", 0)),
                round(bounds.get("Width", 0)),
                round(bounds.get("Height", 0)),
            )
            return frame, str(info[0].get("kCGWindowName") or "")
        except Exception:
            return None

    def _ax_windows(self, pid: int) -> list[Any]:
        try:
            from ApplicationServices import (  # type: ignore[import-not-found]
                AXUIElementCreateApplication,
                kAXWindowsAttribute,
            )
        except ImportError:
            return []
        windows = self._ax_attribute(AXUIElementCreateApplication(pid), kAXWindowsAttribute)
        return list(windows or [])

    def _ax_frame(self, window: Any) -> tuple[int, int, int, int] | None:
        try:
            from ApplicationServices import (  # type: ignore[import-not-found]
                AXValueGetValue,
                kAXPositionAttribute,
                kAXSizeAttribute,
                kAXValueCGPointType,
                kAXValueCGSizeType,
            )

            position = self._ax_attribute(window, kAXPositionAttribute)
            size = self._ax_attribute(window, kAXSizeAttribute)
            if position is None or size is None:
                return None
            has_point, point = AXValueGetValue(position, kAXValueCGPointType, None)
            has_size, extent = AXValueGetValue(size, kAXValueCGSizeType, None)
            if not (has_point and has_size):
                return None
            return round(point.x), round(point.y), round(extent.width), round(extent.height)
        except Exception:
            return None

    def _ax_title(self, window: Any) -> str:
        try:
            from ApplicationServices import kAXTitleAttribute  # type: ignore[import-not-found]
        except ImportError:
            return ""
        return str(self._ax_attribute(window, kAXTitleAttribute) or "")

    def _ax_raise(self, window: Any) -> bool:
        try:
            from ApplicationServices import (  # type: ignore[import-not-found]
                AXUIElementPerformAction,
                AXUIElementSetAttributeValue,
                kAXErrorSuccess,
                kAXMainAttribute,
                kAXRaiseAction,
            )

            if AXUIElementPerformAction(window, kAXRaiseAction) != kAXErrorSuccess:
                return False
            # Activating the app brings its main window forward, so a window
            # that couldn't be made main isn't the one that gets focus.
            return AXUIElementSetAttributeValue(window, kAXMainAttribute, True) == kAXErrorSuccess
        except Exception:
            return False

    @staticmethod
    def _ax_attribute(element: Any, name: Any) -> Any | None:
        try:
            from ApplicationServices import (  # type: ignore[import-not-found]
                AXUIElementCopyAttributeValue,
                kAXErrorSuccess,
            )

            error, value = AXUIElementCopyAttributeValue(element, name, None)
        except Exception:
            return None
        return value if error == kAXErrorSuccess else None

    # ── Apps ─────────────────────────────────────────────────────────

    def app_list(self, *, include_background: bool = False) -> list[AppInfo]:
        try:
            from AppKit import NSWorkspace  # type: ignore[import-not-found]
        except ImportError as exc:
            raise FeatureNotSupportedError("app.list", reason=str(exc)) from exc
        out: list[AppInfo] = []
        for app in NSWorkspace.sharedWorkspace().runningApplications():
            try:
                # 0 = regular (dock-visible), 1 = accessory, 2 = prohibited
                policy = int(app.activationPolicy())
                if not include_background and policy != 0:
                    continue
                out.append(
                    AppInfo(
                        pid=int(app.processIdentifier()),
                        name=str(app.localizedName() or ""),
                        bundle_id=str(app.bundleIdentifier() or "") or None,
                        executable_path=(
                            str(app.executableURL().path()) if app.executableURL() else None
                        ),
                        is_frontmost=bool(app.isActive()),
                        window_count=0,  # NSRunningApplication doesn't expose this
                    )
                )
            except Exception:
                continue
        return out

    def app_launch(
        self,
        *,
        bundle_id: str | None = None,
        executable_path: str | None = None,
        args: list[str] | None = None,
        activate: bool = True,
    ) -> int:
        if bundle_id:
            # `open` passes launch arguments and honours activation (-g keeps
            # the app in the background); NSWorkspace.openURL_ took neither.
            command = ["open", "-b", bundle_id]
            if not activate:
                command.append("-g")
            if args:
                command += ["--args", *args]
            try:
                result = subprocess.run(command, capture_output=True, timeout=30, check=False)
            except (OSError, subprocess.SubprocessError) as exc:
                raise FeatureNotSupportedError("app.launch", reason=str(exc)) from exc
            if result.returncode != 0:
                reason = result.stderr.decode("utf-8", errors="replace").strip()
                raise FeatureNotSupportedError(
                    "app.launch", reason=reason or f"open exited with {result.returncode}"
                )
            # Resolve pid via NSRunningApplication scan.
            for _ in range(20):
                pid = self._pid_for_bundle(bundle_id)
                if pid:
                    return pid
                time.sleep(0.05)
            return 0
        if executable_path:
            proc = subprocess.Popen(
                [executable_path, *(args or [])],
                start_new_session=True,
            )
            return proc.pid
        raise FeatureNotSupportedError(
            "app.launch", reason="either bundle_id or executable_path is required"
        )

    def _pid_for_bundle(self, bundle_id: str) -> int | None:
        try:
            from AppKit import NSRunningApplication  # type: ignore[import-not-found]

            for app in NSRunningApplication.runningApplicationsWithBundleIdentifier_(bundle_id):
                return int(app.processIdentifier())
        except Exception:
            return None
        return None

    # ── Clipboard ────────────────────────────────────────────────────

    def clipboard_read(self, *, format: str = "text") -> ClipboardReadResult:
        if not self._clipboard_enabled:
            raise FeatureNotSupportedError("clipboard.read", reason="--enable-clipboard not set")
        if format != "text":
            raise FeatureNotSupportedError(
                "clipboard.read",
                reason=f"format {format!r} not supported in v1",
            )
        snapshot = self._pasteboard_snapshot()
        if snapshot is None:
            raise ClipboardConcealedError(
                "concealed_type",
                marker="unknown",
                message="the clipboard could not be read consistently",
            )
        text, seq, markers = snapshot
        # Concealed-marker check first. Types that can't be read could be
        # hiding a marker, so they refuse the read too.
        if markers is None:
            raise ClipboardConcealedError(
                "concealed_type",
                marker="unknown",
                message="clipboard contents not readable: its types could not be read",
            )
        for c in CONCEALED_PB_TYPES:
            if c in markers:
                raise ClipboardConcealedError(
                    "concealed_type",
                    marker=c,
                )

        if self._clipboard_read_foreign:
            content = text or ""
            return ClipboardReadResult(
                format="text", content=content, size_bytes=len(content.encode("utf-8"))
            )

        # Default (writeback-only) — must match an in-window record.
        record = self.clipboard_writeback.check(live_content=text, live_sequence=seq)
        if record is None:
            snap = self.clipboard_writeback.snapshot()
            if snap is None:
                raise ClipboardConcealedError("writeback_only")
            age = snap.age()
            if age > self.clipboard_writeback.window_seconds:
                raise ClipboardConcealedError("writeback_only", writeback_age_seconds=age)
            raise ClipboardConcealedError("writeback_overwritten")
        content = text or ""
        return ClipboardReadResult(
            format="text", content=content, size_bytes=len(content.encode("utf-8"))
        )

    def clipboard_write(self, *, format: str = "text", content: str) -> None:
        if not self._clipboard_enabled:
            raise FeatureNotSupportedError("clipboard.write", reason="--enable-clipboard not set")
        if format != "text":
            raise FeatureNotSupportedError(
                "clipboard.write", reason=f"format {format!r} not supported in v1"
            )
        seq = self._write_pasteboard_text(content)
        self.clipboard_writeback.record_write(content, sequence=seq)

    def _pasteboard(self) -> Any | None:
        try:
            from AppKit import NSPasteboard  # type: ignore[import-not-found]

            return NSPasteboard.generalPasteboard()
        except ImportError:
            return None

    def _read_pasteboard_text(self) -> tuple[str | None, int | None]:
        pb = self._pasteboard()
        if pb is None:
            return None, None
        try:
            from AppKit import NSPasteboardTypeString  # type: ignore[import-not-found]

            text = pb.stringForType_(NSPasteboardTypeString)
            return (str(text) if text is not None else None), int(pb.changeCount())
        except Exception:
            return None, None

    def _write_pasteboard_text(self, content: str) -> int:
        """Write `content` and return the new changeCount; raise if the text
        did not land, so nothing acknowledges or pastes a stale clipboard."""
        pb = self._pasteboard()
        if pb is None:
            raise ClipboardWriteError("the pasteboard is unavailable")
        try:
            from AppKit import NSPasteboardTypeString  # type: ignore[import-not-found]

            pb.clearContents()
            written = pb.setString_forType_(content, NSPasteboardTypeString)
            change_count = int(pb.changeCount())
        except Exception as exc:
            raise ClipboardWriteError(str(exc)) from exc
        if not written:
            raise ClipboardWriteError("the pasteboard refused the text")
        return change_count

    def _read_pasteboard_types(self) -> list[str] | None:
        """The pasteboard's types, or None if they can't be read."""
        pb = self._pasteboard()
        if pb is None:
            return None
        try:
            types = pb.types() or []
            return [str(t) for t in types]
        except Exception:
            return None

    def _type(self, text: str, *, paste: bool, preserve_clipboard: bool) -> None:
        import pyautogui  # type: ignore[import-untyped]

        if paste and paste_is_worth_it(text) and self._clipboard_enabled:
            if not preserve_clipboard:
                self._do_paste(text, restore=None)
                return
            # The restore puts back plain text only, so paste only with that
            # text in hand. A clipboard holding anything else (an image, rich
            # text, a concealed password), one that can't be read, or an empty
            # one (clearing it after the paste could beat a slow app to the
            # text) is left alone and the text typed.
            snapshot = self._pasteboard_snapshot()
            if snapshot is not None:
                previous, _, types = snapshot
                if (
                    types is not None
                    and set(types) <= _PLAIN_TEXT_PB_TYPES
                    and previous is not None
                ):
                    self._do_paste(text, restore=previous)
                    return
        ensure_typeable(text)
        pyautogui.write(text, interval=0.02)

    def _pasteboard_snapshot(self) -> tuple[str | None, int, list[str] | None] | None:
        """The text, change count and types as one reading. They come from
        separate queries, so the change count and text must read the same
        after the types as before them, or another app wrote in between;
        retried a few times, then None."""
        for _ in range(3):
            text, count = self._read_pasteboard_text()
            types = self._read_pasteboard_types()
            again, count_again = self._read_pasteboard_text()
            if count is not None and count == count_again and text == again:
                return text, count, types
        return None

    def _do_paste(self, text: str, *, restore: str | None) -> None:
        """Paste `text`, then put `restore` back unless something else has
        written the pasteboard since. With `restore=None` the text stays."""
        import pyautogui  # type: ignore[import-untyped]

        try:
            written_count = self._write_pasteboard_text(text)
        except ClipboardWriteError:
            # clearContents may have gone through before the write failed,
            # taking the user's text with it. It goes back only onto a
            # pasteboard that is still empty: anything on it was copied since.
            if restore is not None and self._read_pasteboard_types() == []:
                try:
                    self._write_pasteboard_text(restore)
                except ClipboardWriteError:
                    logger.warning(
                        "Could not restore the clipboard after a failed write", exc_info=True
                    )
            raise
        # Re-record writeback so the inner read sees us as the writer.
        self.clipboard_writeback.record_write(text, sequence=written_count)
        try:
            pyautogui.hotkey("command", "v")
        finally:
            # Also when the hotkey raised (pyautogui's fail-safe fires before
            # any key goes out): the user's text is already overwritten.
            if restore is not None:
                self._restore_after_paste(text, restore, written_count)

    def _restore_after_paste(self, pasted: str, restore: str, written_count: int) -> None:
        time.sleep(0.05)  # let the paste consume the clipboard
        current, current_count = self._read_pasteboard_text()
        # Restore only if the pasteboard still holds exactly our write. A
        # changed changeCount means the user copied during the paste (compare
        # with what our write left, not the snapshot); other text under our
        # count means a copy landed before we read the count.
        if current_count == written_count and current == pasted:
            # The restored contents are the user's, not ours, so they are
            # not recorded as a writeback: a writeback-only read refuses them.
            try:
                self._write_pasteboard_text(restore)
            except ClipboardWriteError:
                logger.warning("Could not restore the clipboard after pasting", exc_info=True)

    # ── Permissions ──────────────────────────────────────────────────

    def permissions_check(self, permissions: list[str]) -> dict[str, str]:
        out: dict[str, str] = {}
        for p in permissions:
            if p == "accessibility":
                out[p] = "granted" if self._ax_trusted() else "denied"
            elif p == "screen_recording":
                out[p] = "granted" if self._screen_capture_allowed() else "denied"
            elif p == "input_monitoring":
                # No public API short of a probe-and-catch; we conservatively
                # say "unknown" rather than guess.
                out[p] = "unknown"
            else:
                out[p] = "not_applicable"
        return out

    def _ax_trusted(self) -> bool:
        try:
            from ApplicationServices import (  # type: ignore[import-not-found]
                AXIsProcessTrusted,
            )

            return bool(AXIsProcessTrusted())
        except ImportError:
            return False

    def _screen_capture_allowed(self) -> bool:
        try:
            from Quartz import (  # type: ignore[import-not-found]
                CGPreflightScreenCaptureAccess,
            )

            return bool(CGPreflightScreenCaptureAccess())
        except ImportError:
            return False


