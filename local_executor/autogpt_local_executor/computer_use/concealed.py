"""Whether the clipboard holds something a password manager marked private.

Password managers tag what they copy so that clipboard readers leave it
alone: on macOS with the `org.nspasteboard` types, on Windows with a
CF_PRIVATE format or the registered "ExcludeClipboardContentFromMonitor-
Processing" and "Clipboard Viewer Ignore" formats, and on Linux with KDE's
`x-kde-passwordManagerHint` target, which KeePassXC sets as well.
cua-driver reads the clipboard without looking for these, so before and
after relaying a read of content the shim didn't write, it looks here.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
from dataclasses import dataclass

CONCEALED_PASTEBOARD_TYPES = frozenset(
    {
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType",
        "org.nspasteboard.TransientType",
    }
)
CONCEALED_WINDOWS_FORMAT_NAMES = (
    "ExcludeClipboardContentFromMonitorProcessing",
    "Clipboard Viewer Ignore",
)
# CF_PRIVATEFIRST..CF_PRIVATELAST: data an app keeps to itself.
CF_PRIVATE_FIRST = 0x0200
CF_PRIVATE_LAST = 0x02FF
CONCEALED_LINUX_TARGETS = frozenset({"x-kde-passwordManagerHint"})

# What xclip and wl-paste say when the clipboard is empty.
_EMPTY_CLIPBOARD_MESSAGES = ("no owner for", "cannot convert", "not available", "nothing is copied")
_LIST_TIMEOUT_SECONDS = 3.0

UNKNOWN = "unknown"


@dataclass(frozen=True)
class ClipboardState:
    """`marker` names what marks the content private, or is `unknown` when
    the clipboard's types could not be read, which counts as private.
    `sequence` changes with every copy, where the OS keeps one."""

    marker: str | None
    sequence: int | None = None


def marker_in(types: object) -> str | None:
    """A private-content marker among clipboard type names, as cua-driver's
    clipboard_read lists them alongside the text it read."""
    if not isinstance(types, list):
        return None
    names = {str(kind) for kind in types}
    markers = (
        CONCEALED_PASTEBOARD_TYPES
        | CONCEALED_LINUX_TARGETS
        | {name for name in CONCEALED_WINDOWS_FORMAT_NAMES}
    )
    folded = {name.casefold(): name for name in names}
    return next((folded[m.casefold()] for m in sorted(markers) if m.casefold() in folded), None)


def clipboard_state(timeout: float | None = None) -> ClipboardState:
    """The clipboard's marker, looked up within `timeout` seconds where the
    look runs a program (Linux); macOS and Windows ask the OS directly."""
    if sys.platform == "darwin":
        return _macos_state()
    if sys.platform == "win32":
        return _windows_state()
    return _linux_state(timeout)


def _macos_state() -> ClipboardState:
    try:
        from AppKit import NSPasteboard  # type: ignore[import-not-found]

        pasteboard = NSPasteboard.generalPasteboard()
        sequence = int(pasteboard.changeCount())
        types = {str(kind) for kind in (pasteboard.types() or [])}
    except Exception:
        return ClipboardState(UNKNOWN)
    marker = next((kind for kind in sorted(types) if kind in CONCEALED_PASTEBOARD_TYPES), None)
    return ClipboardState(marker, sequence)


def _windows_state() -> ClipboardState:
    try:
        import ctypes

        user32 = ctypes.windll.user32  # type: ignore[attr-defined]
        user32.RegisterClipboardFormatW.restype = ctypes.c_uint
        user32.RegisterClipboardFormatW.argtypes = [ctypes.c_wchar_p]
        user32.IsClipboardFormatAvailable.argtypes = [ctypes.c_uint]
        sequence = int(user32.GetClipboardSequenceNumber())
        # IsClipboardFormatAvailable needs no OpenClipboard, so another app
        # holding the clipboard open can't make the check fail.
        if any(
            user32.IsClipboardFormatAvailable(fmt)
            for fmt in range(CF_PRIVATE_FIRST, CF_PRIVATE_LAST + 1)
        ):
            return ClipboardState("CF_PRIVATE", sequence)
        for name in CONCEALED_WINDOWS_FORMAT_NAMES:
            fmt = user32.RegisterClipboardFormatW(name)
            if fmt and user32.IsClipboardFormatAvailable(fmt):
                return ClipboardState(name, sequence)
        return ClipboardState(None, sequence)
    except Exception:
        return ClipboardState(UNKNOWN)


def linux_clipboard_types_command() -> list[str] | None:
    """The command that lists the clipboard's types on Linux: wl-paste in a
    Wayland session that has it, else xclip with an X display, else None."""
    if os.environ.get("WAYLAND_DISPLAY") and shutil.which("wl-paste"):
        return ["wl-paste", "--list-types"]
    if os.environ.get("DISPLAY") and shutil.which("xclip"):
        return ["xclip", "-selection", "clipboard", "-t", "TARGETS", "-o"]
    return None


def _linux_state(timeout: float | None = None) -> ClipboardState:
    argv = linux_clipboard_types_command()
    limit = _LIST_TIMEOUT_SECONDS if timeout is None else min(timeout, _LIST_TIMEOUT_SECONDS)
    if argv is None or limit <= 0:
        return ClipboardState(UNKNOWN)
    try:
        listed = subprocess.run(
            argv,
            capture_output=True,
            text=True,
            timeout=limit,
            check=False,
        )
    except (OSError, subprocess.SubprocessError):
        return ClipboardState(UNKNOWN)
    if listed.returncode != 0:
        message = (listed.stderr or "").lower()
        if any(text in message for text in _EMPTY_CLIPBOARD_MESSAGES):
            return ClipboardState(None)
        return ClipboardState(UNKNOWN)
    targets = {line.strip() for line in listed.stdout.splitlines() if line.strip()}
    marker = next((t for t in sorted(targets) if t in CONCEALED_LINUX_TARGETS), None)
    return ClipboardState(marker)


